//! Lexicon plane classification for GAIA-2.0 document chunks.
//!
//! Two parallel dictionaries — Order and Chaos — must never be silently conflated.
//! Every `DocumentChunk` emitted by the chunker carries a `LexiconPlane` tag so
//! the RAG pipeline always knows which plane it is pulling from.
//!
//! ## Classification pipeline
//!
//! 1. The chunker sets `lexicon_plane = Bridge` (safe default, C30).
//! 2. The ingestion pipeline calls `classify_document_chunk(&mut chunk)` once
//!    per chunk immediately after chunking.
//! 3. `classify_document_chunk` builds a `LexiconSignals` struct from the
//!    chunk's existing fields (no new I/O), then calls `classify_chunk` to
//!    derive `(LexiconPlane, Option<LexiconVoice>)`, and writes the result
//!    back in-place.
//! 4. Bridge chunks that reach the retrieval layer have genuinely unknown
//!    provenance (e.g. inline runtime-generated text). The retrieval guard
//!    in `gaia-memos` treats Bridge as a pass-through.
//!
//! ## Signal priority (highest to lowest)
//!
//! 1. `attributes["sacred"] == "true"` → always `Chaos / Sacred`.
//! 2. Explicit attribute overrides: `attributes["human_authored"]`,
//!    `attributes["ai_generated"]`.
//! 3. `DocumentKind` inference (`CanonTablet`, `SpecDocument` → Order;
//!    `EpisodeSummary`, `SourceCode` → Order/AI; etc.).
//! 4. `provenance.source` (`DataSource`) inference.
//! 5. Language code — non-English raises Chaos probability for human-authored.
//! 6. Fallback → `Bridge`.
//!
//! Canon: C156 (KG + memory taxonomy), C30 (no silent failures)
//! DB mirror: supabase/migrations/20260923_gaia20_lexicon_order.sql
//!            supabase/migrations/20260923_gaia20_lexicon_chaos.sql

use serde::{Deserialize, Serialize};

