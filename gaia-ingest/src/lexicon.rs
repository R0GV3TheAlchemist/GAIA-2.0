// ── Plane ────────────────────────────────────────────────────────────────────

/// Which ontological plane this chunk's vocabulary belongs to.
///
/// - `Order`  — formal, machine-tractable, AI-authored or standards-body text.
/// - `Chaos`  — lived, cultural, human-authored, contested, or sacred text.
/// - `Bridge` — agreed interface points; safe default when provenance is unknown.
///
/// The chunker sets `Bridge` by default. `classify_document_chunk()` promotes
/// chunks to `Order` or `Chaos` based on document metadata. Promotion is
/// always explicit; the wall between planes is never crossed implicitly.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "PascalCase")]
pub enum LexiconPlane {
    Order,
    Chaos,
    Bridge,
}

impl Default for LexiconPlane {
    /// Safe default: `Bridge`.
    ///
    /// Unknown provenance must not be silently assigned to either plane.
    fn default() -> Self {
        Self::Bridge
    }
}

impl std::fmt::Display for LexiconPlane {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Order  => write!(f, "Order"),
            Self::Chaos  => write!(f, "Chaos"),
            Self::Bridge => write!(f, "Bridge"),
        }
    }
}

// ── Voice ────────────────────────────────────────────────────────────────────

/// Who speaks the vocabulary in this chunk.
///
/// Mirrors the `lexicon_voice` Postgres ENUM.
/// `None` is the safe default — voice is unknown until resolved.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "PascalCase")]
pub enum LexiconVoice {
    /// Authored by a person with lived experience.
    HumanVoice,
    /// Generated or defined by an AI system.
    AIVoice,
    /// Standards body, academic, or regulatory source.
    Institutional,
    /// TEK-gated community knowledge. Retrieval requires explicit grant.
    /// See `gaia-aikd/src/card.rs` `cannot_know()`.
    Sacred,
}

impl std::fmt::Display for LexiconVoice {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::HumanVoice    => write!(f, "HumanVoice"),
            Self::AIVoice       => write!(f, "AIVoice"),
            Self::Institutional => write!(f, "Institutional"),
            Self::Sacred        => write!(f, "Sacred"),
        }
    }
}

// ── LexiconSignals ────────────────────────────────────────────────────────────

/// Signals used by the ingestion pipeline to classify a chunk's lexicon plane.
///
/// These are derived from document-level metadata, not from the chunk text
/// itself. The chunker does not read content to classify — it reads provenance.
#[derive(Debug, Clone, Default)]
pub struct LexiconSignals {
    /// Source document was authored by a human (not AI-generated).
    pub human_authored: bool,
    /// Source document was generated by an AI system.
    pub ai_generated: bool,
    /// Standards body, academic, or regulatory source.
    pub institutional: bool,
    /// Language code (BCP-47). Non-English codes raise the probability of
    /// Chaos classification due to cultural embeddedness.
    pub language_code: Option<String>,
    /// Domain from `card.rs`. Some domains (e.g. `law`, `health`) have
    /// higher Chaos risk for human-authored content.
    pub domain: Option<String>,
    /// Explicit sacred/TEK flag from document metadata or consent record.
    pub sacred: bool,
}

// ── classify_chunk ────────────────────────────────────────────────────────────

/// Classify a chunk's lexicon plane from ingestion signals.
///
/// Rules (in priority order):
/// 1. Sacred flag → `Chaos / Sacred`.
/// 2. `human_authored` + non-English → `Chaos / HumanVoice`.
/// 3. `institutional` → `Order / Institutional`.
/// 4. `ai_generated` → `Order / AIVoice`.
/// 5. `human_authored` → `Chaos / HumanVoice`.
/// 6. Fallback → `Bridge / None`.
///
/// # Examples
///
/// ```rust
/// use gaia_ingest::lexicon::{classify_chunk, LexiconSignals, LexiconPlane, LexiconVoice};
///
/// let signals = LexiconSignals { ai_generated: true, ..Default::default() };
/// let (plane, voice) = classify_chunk(&signals);
/// assert_eq!(plane, LexiconPlane::Order);
/// assert_eq!(voice, Some(LexiconVoice::AIVoice));
/// ```
pub fn classify_chunk(signals: &LexiconSignals) -> (LexiconPlane, Option<LexiconVoice>) {
    if signals.sacred {
        return (LexiconPlane::Chaos, Some(LexiconVoice::Sacred));
    }

    let non_english = signals
        .language_code
        .as_deref()
        .map(|lc| !lc.starts_with("en"))
        .unwrap_or(false);

    if signals.human_authored && non_english {
        return (LexiconPlane::Chaos, Some(LexiconVoice::HumanVoice));
    }

    if signals.institutional {
        return (LexiconPlane::Order, Some(LexiconVoice::Institutional));
    }

    if signals.ai_generated {
        return (LexiconPlane::Order, Some(LexiconVoice::AIVoice));
    }

    if signals.human_authored {
        return (LexiconPlane::Chaos, Some(LexiconVoice::HumanVoice));
    }

    (LexiconPlane::Bridge, None)
}

// ── signals_from_chunk ────────────────────────────────────────────────────────

/// Derive `LexiconSignals` from the existing fields of a `DocumentChunk`.
///
/// Signal extraction follows a strict priority order — explicit `attributes`
/// override inferred `DataSource` / `DocumentKind` signals:
///
/// | Priority | Source | Signal |
/// |---|---|---|
/// | 1 (highest) | `attributes["sacred"] == "true"` | `sacred = true` |
/// | 2 | `attributes["human_authored"] == "true"` | `human_authored = true` |
/// | 2 | `attributes["ai_generated"] == "true"` | `ai_generated = true` |
/// | 3 | `DocumentKind` | see table below |
/// | 4 | `DataSource` | see table below |
/// | 5 (lowest) | `language` field | `language_code` |
///
/// ### DocumentKind → signals
///
/// | Kind | Signal |
/// |---|---|
/// | `CanonTablet` | `institutional = true` (sacred GAIA primary sources) |
/// | `SpecDocument` | `institutional = true` (authoritative spec) |
/// | `EpisodeSummary` | `ai_generated = true` (produced by `gaia-memos`) |
/// | `SourceCode` | `ai_generated = true` (machine-readable formal language) |
/// | `ResearchDocument` | no signal — defer to DataSource / attributes |
/// | `Other` | no signal — defer to DataSource / attributes |
///
/// ### DataSource → signals
///
/// | Source | Signal |
/// |---|---|
/// | `CanonTablet` | `institutional = true` |
/// | `SpecDocument` | `institutional = true` |
/// | `GbifOccurrence`, `GbifSpecies` | `institutional = true` (GBIF = standards body) |
/// | `Noaa`, `Copernicus`, `SentinelHub` | `institutional = true` (government/ESA) |
/// | `SensorThings` | `ai_generated = true` (machine sensor) |
/// | `ManualEntry` | `human_authored = true` |
/// | `ApiEndpoint` | `ai_generated = true` (machine-generated response) |
/// | others | no signal |
///
/// Attribute overrides (priority 2) always win over kind/source inference
/// (priorities 3–4), except `sacred` which is always highest priority.
pub fn signals_from_chunk(chunk: &DocumentChunk) -> LexiconSignals {
    let mut signals = LexiconSignals {
        language_code: Some(chunk.language.clone()),
        domain: Some(chunk.domain.clone()),
        ..Default::default()
    };

    // ── Priority 3: DocumentKind inference ──────────────────────────────────
    match chunk.kind {
        DocumentKind::CanonTablet | DocumentKind::SpecDocument => {
            signals.institutional = true;
        }
        DocumentKind::EpisodeSummary | DocumentKind::SourceCode => {
            signals.ai_generated = true;
        }
        DocumentKind::ResearchDocument | DocumentKind::Other => {
            // No kind-level signal; fall through to DataSource.
        }
    }

    // ── Priority 4: DataSource inference ────────────────────────────────────
    // Only apply if kind didn't already set a signal.
    if !signals.institutional && !signals.ai_generated && !signals.human_authored {
        match chunk.provenance.source {
            DataSource::CanonTablet | DataSource::SpecDocument => {
                signals.institutional = true;
            }
            DataSource::GbifOccurrence
            | DataSource::GbifSpecies
            | DataSource::Noaa
            | DataSource::Copernicus
            | DataSource::SentinelHub => {
                signals.institutional = true;
            }
            DataSource::SensorThings | DataSource::ApiEndpoint => {
                signals.ai_generated = true;
            }
            DataSource::ManualEntry => {
                signals.human_authored = true;
            }
            // OsmFeature, S3Artifact, Unknown — no signal; remain Bridge.
            _ => {}
        }
    }

    // ── Priority 2: Explicit attribute overrides ─────────────────────────────
    // These win over kind/source inference above.
    if chunk.attributes.get("human_authored").map(|v| v == "true").unwrap_or(false) {
        signals.ai_generated    = false;
        signals.institutional   = false;
        signals.human_authored  = true;
    }
    if chunk.attributes.get("ai_generated").map(|v| v == "true").unwrap_or(false) {
        signals.human_authored  = false;
        signals.institutional   = false;
        signals.ai_generated    = true;
    }

    // ── Priority 1: Sacred flag ──────────────────────────────────────────────
    // Wins over everything — set last so nothing above can clear it.
    if chunk.attributes.get("sacred").map(|v| v == "true").unwrap_or(false) {
        signals.sacred = true;
    }

    signals
}

// ── classify_document_chunk ──────────────────────────────────────────────────

/// Classify `chunk.lexicon_plane` and `chunk.lexicon_voice` in-place.
///
/// This is the **single call-site** the ingestion pipeline must use after
/// chunking. It derives signals from the chunk's existing provenance fields
/// via `signals_from_chunk()`, runs `classify_chunk()`, and writes the result
/// back.
///
/// ## Idempotency
///
/// If `chunk.lexicon_plane != Bridge` this function is a no-op — the chunk
/// was already classified (e.g. by a prior pipeline stage or an explicit
/// override) and must not be silently re-classified.
///
/// ## Usage
///
/// ```rust,ignore
/// use gaia_ingest::lexicon::classify_document_chunk;
///
/// for chunk in chunker.chunks_mut() {
///     classify_document_chunk(chunk);
/// }
/// ```
pub fn classify_document_chunk(chunk: &mut DocumentChunk) {
    // Idempotency guard: don't overwrite an explicit classification.
    if chunk.lexicon_plane != LexiconPlane::Bridge {
        return;
    }

    let signals = signals_from_chunk(chunk);
    let (plane, voice) = classify_chunk(&signals);

    chunk.lexicon_plane = plane;
    // Only write voice if classification resolved it — preserve None for
    // genuine Bridge chunks where voice is also unknown.
    if voice.is_some() {
        chunk.lexicon_voice = voice;
    }
}

